#!/usr/bin/env python3
"""Build a compact item-name autocomplete index from the pinned Forever client."""

from __future__ import annotations

import csv
import hashlib
from pathlib import Path
import unicodedata


ROOT = Path(__file__).resolve().parents[1]
CLIENT_BUILD = "1.60.1.70959"
LOCALES = ("ruRU", "enUS")
SOURCE_PATHS = {
    "ruRU": ROOT / "vendor" / "wago" / CLIENT_BUILD / "ItemSparse.csv",
    "enUS": ROOT / "vendor" / "wago" / CLIENT_BUILD / "ItemSparse.enUS.csv",
}
SOURCE_PATH = SOURCE_PATHS["ruRU"]
OUTPUT_PATH = ROOT / "Foreverpedia_Data" / "Search.lua"


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def normalize(value: str) -> str:
    return " ".join(
        unicodedata.normalize("NFKC", value).casefold().replace("ё", "е").split()
    )


def lua_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') \
        .replace("\n", "\\n").replace("\r", "") + '"'


def read_items(path: Path = SOURCE_PATH) -> dict[int, tuple[str, str]]:
    items: dict[int, tuple[str, str]] = {}
    with path.open(encoding="utf-8-sig", newline="") as stream:
        for row in csv.DictReader(stream):
            item_id = int(row["ID"])
            name = row["Display_lang"].strip()
            if not name:
                continue
            normalized = normalize(name)
            if normalized:
                items[item_id] = (name, normalized)
    return items


def build_lua(
    localized_items: dict[str, dict[int, tuple[str, str]]],
    source_hashes: dict[str, str],
) -> str:
    lines = [
        "local _, Data = ...",
        "",
        "-- Generated by tools/build_search_database.py; do not edit by hand.",
        "Data.ItemSearchData = {",
        "    manifest = {",
        '        source = "WoW client ItemSparse",',
        f"        version = {lua_string(CLIENT_BUILD)},",
        "        locales = {",
    ]
    for locale in LOCALES:
        lines.append(
            f"            {locale} = {{sha256={lua_string(source_hashes[locale])},"
            f"itemCount={len(localized_items[locale])}}},"
        )
    lines.extend([
        "        },",
        "    },",
        "    items = {",
    ])
    for locale in LOCALES:
        lines.append(f"        {locale} = {{")
        for item_id, (name, normalized) in sorted(localized_items[locale].items()):
            lines.append(
                f"            [{item_id}] = {{{lua_string(name)},{lua_string(normalized)}}},"
            )
        lines.append("        },")
    lines.extend(["    },", "}", ""])
    return "\n".join(lines)


def generate(
    source_paths: dict[str, Path] = SOURCE_PATHS,
    output_path: Path = OUTPUT_PATH,
) -> dict[str, dict[int, tuple[str, str]]]:
    localized_items = {}
    source_hashes = {}
    for locale in LOCALES:
        source_path = source_paths[locale]
        if not source_path.is_file():
            raise FileNotFoundError(f"missing {locale} client DB2 export: {source_path}")
        localized_items[locale] = read_items(source_path)
        source_hashes[locale] = sha256(source_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(
        build_lua(localized_items, source_hashes), encoding="utf-8", newline="\n"
    )
    return localized_items


if __name__ == "__main__":
    data = generate()
    counts = ", ".join(f"{locale}: {len(data[locale])}" for locale in LOCALES)
    print(f"Generated autocomplete indexes ({counts}) from build {CLIENT_BUILD}")
